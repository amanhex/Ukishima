var _all = null;

/** Every emoji, parsed once: { glyph, keys }. */
function all() {
    if (_all)
        return _all;
    var out = [];
    for (var i = 0; i < DATA.length; i++) {
        var tab = DATA[i].indexOf("\t");
        out.push({
            glyph: tab > 0 ? DATA[i].substring(0, tab) : DATA[i],
            keys: tab > 0 ? DATA[i].substring(tab + 1).toLowerCase() : ""
        });
    }
    _all = out;
    return _all;
}

/** Emoji whose name or keywords contain every word of the query. Name matches
 * come first, then whole-word matches, then loose substring hits (so "cat"
 * starts with the cats instead of the intoxi-cat-ed corner of the table). */
function search(query) {
    var src = all();
    var q = String(query || "").trim().toLowerCase();
    if (!q)
        return src;
    var words = q.split(/\s+/);
    var name = [], word = [], loose = [];
    for (var i = 0; i < src.length; i++) {
        var keys = src[i].keys;
        var hit = true;
        for (var w = 0; w < words.length; w++) {
            if (keys.indexOf(words[w]) === -1) {
                hit = false;
                break;
            }
        }
        if (!hit)
            continue;
        if (keys.indexOf(q) === 0)
            name.push(src[i]);
        else if ((" " + keys).indexOf(" " + q) !== -1)
            word.push(src[i]);
        else
            loose.push(src[i]);
    }
    return name.concat(word, loose);
}
